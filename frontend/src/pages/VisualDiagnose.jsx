import { useRef, useState, useCallback, useEffect } from 'react'
import { api } from '../api/client.js'
import DiagnosisResultView from '../components/DiagnosisResultView.jsx'
import ImageCropper from '../components/ImageCropper.jsx'

const MAX_IMAGE_BYTES = 10 * 1024 * 1024 // matches visualUploadMiddleware on the backend
const ACCEPTED = 'image/png,image/jpeg,image/jpg,image/webp,image/gif,image/bmp'

function formatBytes(bytes) {
  if (!bytes) return '0 KB'
  const kb = bytes / 1024
  if (kb < 1024) return `${Math.round(kb)} KB`
  return `${(kb / 1024).toFixed(1)} MB`
}

function validateFile(selected) {
  if (!selected) return 'No file was selected.'
  if (!selected.type.startsWith('image/')) {
    return 'That is not an image. Upload a screenshot (PNG, JPG, WebP or GIF).'
  }
  if (selected.size > MAX_IMAGE_BYTES) {
    return `That image is ${formatBytes(selected.size)}. The maximum size is 10 MB.`
  }
  return ''
}

export default function VisualDiagnose() {
  const [file, setFile] = useState(null) // what will actually be uploaded
  const [originalFile, setOriginalFile] = useState(null) // kept so a crop can be undone
  const [previewUrl, setPreviewUrl] = useState('')
  const [cropOpen, setCropOpen] = useState(false)
  const [cropInfo, setCropInfo] = useState(null)
  const [context, setContext] = useState('')
  const [loading, setLoading] = useState(false)
  const [elapsed, setElapsed] = useState(0)
  const [error, setError] = useState('')
  const [rawResponse, setRawResponse] = useState('')
  const [result, setResult] = useState(null)
  const [diagnosisId, setDiagnosisId] = useState(null)
  const [copied, setCopied] = useState(false)
  const [verifyStatus, setVerifyStatus] = useState(null)
  const [verifyNotes, setVerifyNotes] = useState('')
  const [verifySubmitting, setVerifySubmitting] = useState(false)
  const [verifySaved, setVerifySaved] = useState(false)
  const [dragActive, setDragActive] = useState(false)
  const [contextFocus, setContextFocus] = useState(false)
  const fileInputRef = useRef(null)
  const contextRef = useRef(null)
  const dragDepth = useRef(0)

  // Object URLs leak until they are revoked, and this page can be re-entered
  // many times in a session, so tie the lifetime of each preview to the file.
  useEffect(() => {
    return () => {
      if (previewUrl) URL.revokeObjectURL(previewUrl)
    }
  }, [previewUrl])

  const processFile = useCallback((selected) => {
    const problem = validateFile(selected)
    setResult(null)
    setDiagnosisId(null)
    setVerifySaved(false)
    setCropInfo(null)
    setError(problem)
    if (problem) {
      setFile(null)
      setOriginalFile(null)
      setPreviewUrl('')
      return
    }
    setFile(selected)
    setOriginalFile(selected)
    setPreviewUrl((old) => {
      if (old) URL.revokeObjectURL(old)
      return URL.createObjectURL(selected)
    })
  }, [])

  // A plain markdown report is the thing a user can actually paste into a
  // ticket or hand to a colleague, which the in-app view does not allow.
  function downloadReport() {
    const lines = [
      `# Visual diagnosis`,
      ``,
      `**Problem:** ${result.problem || 'n/a'}`,
      `**Confidence:** ${Number.isFinite(Number(result.confidence)) ? `${Math.round(Number(result.confidence))}%` : 'n/a'}`,
      result.userContext ? `**Context given:** ${result.userContext}` : null,
      ``,
      `## Root cause`,
      result.rootCause || 'n/a',
      ``,
      `## Fix`,
      result.solution || 'n/a',
      ``,
      result.steps?.length ? `## Steps\n${result.steps.map((s, i) => `${i + 1}. ${s}`).join('\n')}\n` : null,
      result.verification?.length
        ? `## How to verify\n${result.verification.map((v) => `- ${v}`).join('\n')}\n`
        : null,
      result.warnings?.length ? `## Watch out\n${result.warnings.map((w) => `- ${w}`).join('\n')}\n` : null,
      result.evidence?.length ? `## What the screenshot showed\n${result.evidence.map((e) => `- ${e}`).join('\n')}\n` : null,
      `---`,
      `Generated by TechPilot from a screenshot${diagnosisId ? ` · report ${diagnosisId}` : ''}`
    ].filter((l) => l !== null)

    const url = URL.createObjectURL(new Blob([lines.join('\n')], { type: 'text/markdown' }))
    const a = document.createElement('a')
    a.href = url
    a.download = 'visual-diagnosis.md'
    a.click()
    URL.revokeObjectURL(url)
  }

  // The cropper returns a bare Blob with no name, so the file sent to the
  // server is rebuilt from it with a PNG name and extension.
  function applyCrop(blob, info) {
    const cropped = new File([blob], originalFile?.name || 'screenshot.png', { type: 'image/png' })
    setFile(cropped)
    setCropInfo(info)
    setCropOpen(false)
    setResult(null)
    setDiagnosisId(null)
    setVerifySaved(false)
    setPreviewUrl((old) => {
      if (old) URL.revokeObjectURL(old)
      return URL.createObjectURL(blob)
    })
  }

  function restoreFullImage() {
    if (!originalFile) return
    setFile(originalFile)
    setCropInfo(null)
    setPreviewUrl((old) => {
      if (old) URL.revokeObjectURL(old)
      return URL.createObjectURL(originalFile)
    })
  }

  function handleFileChange(e) {
    processFile(e.target.files && e.target.files[0])
  }

  function handleClear() {
    setFile(null)
    setOriginalFile(null)
    setPreviewUrl('')
    setResult(null)
    setError('')
    setRawResponse('')
    setDiagnosisId(null)
    setCropInfo(null)
    setVerifySaved(false)
    setVerifyStatus(null)
    setVerifyNotes('')
    if (fileInputRef.current) fileInputRef.current.value = ''
  }

  // dragenter/dragleave fire for every child element, so a naive toggle makes
  // the zone flicker. Counting enter/leave pairs keeps the highlight stable.
  function handleDragEnter(e) {
    e.preventDefault()
    e.stopPropagation()
    dragDepth.current += 1
    setDragActive(true)
  }

  function handleDragOver(e) {
    e.preventDefault()
    e.stopPropagation()
    setDragActive(true)
  }

  function handleDragLeave(e) {
    e.preventDefault()
    e.stopPropagation()
    dragDepth.current = Math.max(0, dragDepth.current - 1)
    if (dragDepth.current === 0) setDragActive(false)
  }

  function handleDrop(e) {
    e.preventDefault()
    e.stopPropagation()
    dragDepth.current = 0
    setDragActive(false)
    processFile(e.dataTransfer.files && e.dataTransfer.files[0])
  }

  function openPicker() {
    fileInputRef.current?.click()
  }

  function handleKeyDown(e) {
    if (e.key === 'Enter' || e.key === ' ') {
      e.preventDefault()
      openPicker()
    }
  }

  // The vision model can take a minute on a cold start, so the wait is
  // counted rather than left as an indefinite spinner.
  useEffect(() => {
    if (!loading) {
      setElapsed(0)
      return undefined
    }
    const started = Date.now()
    const id = setInterval(() => setElapsed(Math.round((Date.now() - started) / 1000)), 500)
    return () => clearInterval(id)
  }, [loading])

  async function handleSubmit(e) {
    e.preventDefault()
    if (!file) {
      setError('Choose a screenshot first.')
      return
    }

    setLoading(true)
    setError('')
    setRawResponse('')
    setResult(null)
    setVerifySaved(false)
    setVerifyStatus(null)
    setVerifyNotes('')

    try {
      const formData = new FormData()
      formData.append('image', file)
      if (context.trim()) formData.append('context', context.trim())
      const data = await api.postForm('/api/agents/visual', formData)
      setResult(data.result)
      setDiagnosisId(data.diagnosisId || null)
    } catch (err) {
      setError(err.message || 'Failed to analyze the screenshot')
      // The server returns the model's unparsable output on a 502. On a small
      // vision model that happens often enough to be worth seeing.
      setRawResponse(err.data?.rawResponse || '')
    } finally {
      setLoading(false)
    }
  }

  async function handleVerify(status) {
    setVerifyStatus(status)
    setVerifySubmitting(true)
    setError('')
    try {
      await api.post('/api/verification', {
        problem: result.problem,
        solution: result.solution,
        status,
        notes: verifyNotes || undefined,
        diagnosisId: diagnosisId || undefined
      })
      setVerifySaved(true)
    } catch (err) {
      setError(err.message)
    } finally {
      setVerifySubmitting(false)
    }
  }

  const confidenceLow =
    result && Number.isFinite(Number(result.confidence)) && Number(result.confidence) < 55

  // The context box sits above the result, so after a low-confidence read the
  // page scrolls back to it instead of leaving the user hunting for the field.
  useEffect(() => {
    if (contextFocus && contextRef.current) {
      contextRef.current.focus()
      contextRef.current.scrollIntoView({ behavior: 'smooth', block: 'center' })
      setContextFocus(false)
    }
  }, [contextFocus])

  async function copyFix() {
    if (!result) return
    const parts = [result.rootCause, result.solution, ...(result.steps || [])].filter(Boolean)
    try {
      await navigator.clipboard.writeText(parts.join('\n\n'))
      setCopied(true)
      setTimeout(() => setCopied(false), 1500)
    } catch {
      setCopied(false)
    }
  }

  // Paste a screenshot straight from the clipboard.
  useEffect(() => {
    function handlePaste(e) {
      if (loading || result) return
      const items = e.clipboardData?.items
      if (!items) return

      for (const item of items) {
        if (item.type.startsWith('image/')) {
          const blob = item.getAsFile()
          if (blob) {
            e.preventDefault()
            processFile(blob)
            break
          }
        }
      }
    }

    window.addEventListener('paste', handlePaste)
    return () => window.removeEventListener('paste', handlePaste)
  }, [loading, result, processFile])

  return (
    <div className="vd-page">
      <div className="vd-header">
        <div className="vd-header-icon">
          <i className="fa-solid fa-eye"></i>
        </div>
        <div>
          <h1 className="vd-title">Visual Diagnose</h1>
          <p className="vd-subtitle">
            Upload a screenshot of an error or a broken screen. The vision model reads it and
            describes the problem, the likely root cause and how to fix it.
          </p>
        </div>
      </div>

      <form onSubmit={handleSubmit}>
        <div
          className={`vd-dropzone ${dragActive ? 'active' : ''} ${file ? 'has-file' : ''}`}
          onDragEnter={handleDragEnter}
          onDragOver={handleDragOver}
          onDragLeave={handleDragLeave}
          onDrop={handleDrop}
          onClick={file ? undefined : openPicker}
          onKeyDown={handleKeyDown}
          role="button"
          tabIndex={0}
          aria-label="Upload a screenshot"
        >
          <input
            ref={fileInputRef}
            type="file"
            accept={ACCEPTED}
            onChange={handleFileChange}
            className="vd-file-input"
          />

          {file && previewUrl ? (
            <div className="vd-preview-wrap">
              <img src={previewUrl} alt="Selected screenshot preview" className="vd-preview" />
              <div className="vd-file-meta">
                <div className="vd-file-name">
                  {file.name}
                  {cropInfo && <span className="vd-crop-badge">cropped</span>}
                </div>
                <div className="vd-file-size">{formatBytes(file.size)}</div>
              </div>
            </div>
          ) : (
            <div className="vd-empty">
              <i className="fa-solid fa-cloud-arrow-up vd-empty-icon"></i>
              <div className="vd-empty-title">Drag &amp; drop a screenshot here</div>
              <div className="vd-empty-hint">
                or click to browse &middot; paste with Ctrl+V &middot; PNG, JPG, WebP, GIF up to 10 MB
              </div>
            </div>
          )}
        </div>

        {file && (
          <>
            <label className="vd-context">
              <span className="vd-context-label">
                Extra context
                <em>optional, but it makes a large difference</em>
              </span>
              <textarea
                ref={contextRef}
                rows={2}
                value={context}
                onChange={(e) => setContext(e.target.value)}
                placeholder="What were you doing, which app or service is this, when did it start? e.g. &quot;Postgres admin page, after I changed the connection string in staging&quot;"
                maxLength={2000}
              />
            </label>

            <div className="vd-actions">
              <button type="submit" className="vd-btn-primary" disabled={loading}>
                {loading ? (
                  <>
                    <i className="fa-solid fa-circle-notch fa-spin"></i>
                    Analyzing screenshot... {elapsed}s
                  </>
                ) : (
                  <>
                    <i className="fa-solid fa-magnifying-glass-chart"></i>
                    Analyze Screenshot
                  </>
                )}
              </button>
              <button
                type="button"
                className="vd-btn-ghost"
                onClick={() => setCropOpen(true)}
                disabled={loading}
              >
                <i className="fa-solid fa-crop-simple"></i>
                {cropInfo ? 'Re-crop' : 'Crop'}
              </button>
              {cropInfo && (
                <button
                  type="button"
                  className="vd-btn-ghost"
                  onClick={restoreFullImage}
                  disabled={loading}
                >
                  <i className="fa-solid fa-expand"></i>
                  Use full image
                </button>
              )}
              <button type="button" className="vd-btn-ghost" onClick={handleClear} disabled={loading}>
                <i className="fa-solid fa-rotate-left"></i>
                Clear
              </button>
            </div>
          </>
        )}
      </form>

      {cropOpen && previewUrl && (
        <ImageCropper
          src={previewUrl}
          onApply={applyCrop}
          onCancel={() => setCropOpen(false)}
        />
      )}

      {error && (
        <div className="vd-error">
          <i className="fa-solid fa-circle-exclamation"></i>
          <div>
            <div>{error}</div>

            {rawResponse && (
              <details className="mt-2">
                <summary className="cursor-pointer text-xs font-medium">
                  What the model actually returned
                </summary>
                <pre className="exec-json mt-2">{rawResponse}</pre>
              </details>
            )}

            {file && !loading && (
              <button type="button" className="vd-btn-ghost mt-3" onClick={handleSubmit}>
                <i className="fa-solid fa-rotate-right"></i>
                Try again
              </button>
            )}
          </div>
        </div>
      )}

      {loading && (
        <div className="vd-thinking">
          <div className="vd-thinking-bar"></div>
          <p className="vd-thinking-text">
            The vision model is reading the screenshot. A first run can take a minute while the
            model loads.
          </p>
        </div>
      )}

      {result && (
        <div className="vd-result">
          <div className="vd-result-bar">
            <span className="vd-result-label">
              <i className="fa-solid fa-wand-magic-sparkles"></i>
              Read from the screenshot
            </span>
            <span className="vd-result-actions">
              {Number.isFinite(Number(result.confidence)) && (
                <span className="vd-confidence">{Math.round(Number(result.confidence))}% confidence</span>
              )}
              <button type="button" className="vd-btn-ghost" onClick={copyFix}>
                {copied ? 'Copied' : 'Copy fix'}
              </button>
              <button type="button" className="vd-btn-ghost" onClick={downloadReport}>
                <i className="fa-solid fa-download"></i>
                Download
              </button>
              {diagnosisId && (
                <a className="vd-btn-ghost" href={`/diagnosis/${diagnosisId}`}>
                  Open full report
                </a>
              )}
            </span>
          </div>

          {confidenceLow && (
            <div className="vd-nudge">
              <i className="fa-solid fa-triangle-exclamation"></i>
              <div>
                <strong>This read is uncertain.</strong> The model is not sure it could read the
                screenshot. Two things usually fix it: crop tighter onto the actual error text, and
                fill in the context box with what you were doing.
                <div className="vd-nudge-actions">
                  <button type="button" className="vd-btn-ghost" onClick={() => setCropOpen(true)}>
                    <i className="fa-solid fa-crop-simple"></i>
                    Crop tighter
                  </button>
                  <button
                    type="button"
                    className="vd-btn-ghost"
                    onClick={() => setContextFocus(true)}
                  >
                    <i className="fa-solid fa-pen"></i>
                    Add context
                  </button>
                  <button type="button" className="vd-btn-ghost" onClick={handleSubmit}>
                    <i className="fa-solid fa-rotate-right"></i>
                    Re-run
                  </button>
                </div>
              </div>
            </div>
          )}

          <DiagnosisResultView result={result} />

          <div className="vd-verify">
            <h2>Did this solution work?</h2>
            {verifySaved ? (
              <p className="vd-verify-saved">
                Marked as <strong>{verifyStatus}</strong>
                {diagnosisId ? ' and linked to this diagnosis' : ''}. This feeds the success rate on
                your dashboard.
              </p>
            ) : (
              <>
                <p className="vd-verify-hint">
                  Rating the answer is what makes the accuracy numbers on the dashboard real.
                </p>
                <textarea
                  rows={2}
                  placeholder="Notes (optional)"
                  value={verifyNotes}
                  onChange={(e) => setVerifyNotes(e.target.value)}
                />
                <div className="vd-verify-buttons">
                  <button disabled={verifySubmitting} onClick={() => handleVerify('success')}>
                    Worked
                  </button>
                  <button disabled={verifySubmitting} onClick={() => handleVerify('partial')}>
                    Partially worked
                  </button>
                  <button disabled={verifySubmitting} onClick={() => handleVerify('failed')}>
                    Didn't work
                  </button>
                </div>
              </>
            )}
          </div>
        </div>
      )}

      {!file && !result && (
        <div className="vd-tips">
          <h2>Crop closer than feels natural</h2>
          <ul>
            <li>Frame the error dialog or message, not the whole desktop</li>
            <li>Include the window title so the app is identifiable</li>
            <li>Hide anything sensitive, and blur tokens or customer data</li>
            <li>Keep the full resolution. Shrinking loses the text the model needs to read</li>
          </ul>
        </div>
      )}
    </div>
  )
}
